"""Write the root apm.yml: the whole catalog as one install, each pack pinned to its release tag.

    python tooling/root_manifest.py          # rewrite apm.yml from the packs' versions
    python tooling/root_manifest.py --check  # exit 1 when apm.yml is out of date (CI)
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCATION = "hybridcloudworks/AgentPacks"
HEADER = f"""# The whole catalog as one install: `apm install {LOCATION}` (or `-g` for the user profile)
# pulls every released pack at its release tag. Each pack is also installable on its own:
# `apm install {LOCATION}/<pack>#<pack-name>-vX.Y.Z`. This file is generated by
# tooling/root_manifest.py from the packs' apm.yml versions; do not edit the list by hand.
"""


def pack_version(pack: Path) -> str:
    match = re.search(r"^version:\s*(\S+)", (pack / "apm.yml").read_text(encoding="utf-8"), re.M)
    if not match:
        raise SystemExit(f"{pack.name}/apm.yml has no version")
    return match.group(1)


def render() -> str:
    packs = sorted(p for p in ROOT.iterdir() if p.is_dir() and p.name.endswith("-pack") and (p / "apm.yml").is_file())
    deps = "\n".join(f"    - {LOCATION}/{p.name}#{p.name[:-5]}-v{pack_version(p)}" for p in packs)
    return (
        HEADER
        + "name: agent-packs\nversion: 1.0.0\ndescription: Every agent pack in this catalog, pinned to its release tag.\n"
        + f"author: hybridcloudworks\nlicense: MIT\nrepository: https://github.com/{LOCATION}\n"
        + "targets:\n  - copilot\n  - claude\n  - codex\n  - kiro\n  - gemini\n  - agent-skills\n"
        + f"dependencies:\n  apm:\n{deps}\n  mcp: []\n"
    )


def main(argv: list[str]) -> int:
    text = render()
    target = ROOT / "apm.yml"
    if "--check" in argv:
        current = target.read_text(encoding="utf-8").replace("\r\n", "\n") if target.is_file() else ""
        if current != text:
            print("apm.yml is out of date: run python tooling/root_manifest.py", file=sys.stderr)
            return 1
        print("apm.yml is current")
        return 0
    target.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote apm.yml with {text.count(chr(10) + '    - ')} packs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
