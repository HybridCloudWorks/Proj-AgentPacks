#!/usr/bin/env python3
"""Build this pack's distributable outputs from the canonical .apm/ source.

Produces, under dist/ (ignored by git, regenerated on every build):
  <target>-<name>.zip         one per APM target, generated by `apm install --target <t>` into a scratch project
  <name>-canonical.zip        apm.yml + .apm/
  <name>-prompt.zip           the authoring prompt
  <name>-validation.zip       VALIDATION_REPORT.md, compatibility/, tests/, templates/
  skills/<skill>/skill.zip    one per skill, plus <name>-skills.zip bundling them
  <name>-full-pack.zip        every source file in the pack
  SHA256SUMS.txt
Also rewrites AGENT-PACK-README.md, the artifact catalog (file, purpose, location; no contents).

Usage: python tooling/build_pack.py [--no-vendor]
"""
from __future__ import annotations

import argparse
import hashlib
import re
import shutil
import subprocess
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIST = ROOT / "dist"
EXCLUDE_DIRS = {"dist", "__pycache__", ".git", ".pytest_cache"}
PURPOSE = {
    "apm.yml": "APM manifest: name, version, targets.",
    "DESCRIPTION.md": "What the pack is for and who uses it.",
    "README.md": "How to install and use the pack.",
    "AGENT-PACK-README.md": "This catalog.",
    "PORTABLE_AGENT_SKILL_PACK_AUTHORING_PROMPT.md": "The master prompt this pack was built to.",
    "LICENSE": "License terms.",
    "VALIDATION_REPORT.md": "Executed checks and what remains unverified.",
}
FOLDER_PURPOSE = {
    ".apm/agents": "Canonical agent", ".apm/skills": "Canonical skill", ".apm/instructions": "Canonical instruction",
    ".apm/prompts": "Canonical prompt", "docs": "Pack contract or inventory", "compatibility": "Vendor compatibility metadata",
    "examples/repository": "Optional repository-level file", "examples": "Worked example", "templates": "Reusable template",
    "hooks/samples": "Reviewed hook sample, not installed", "hooks": "Hook helper script",
    "tests": "Local test or recorded evidence", "tooling": "Build, validation, or hook runner code",
}


def manifest() -> dict[str, object]:
    data: dict[str, object] = {}
    key = None
    for raw in (ROOT / "apm.yml").read_text(encoding="utf-8").splitlines():
        line = raw.rstrip()
        if not line or line.lstrip().startswith("#"):
            continue
        if re.match(r"^\s*-\s+", line) and key:
            data.setdefault(key, [])
            if isinstance(data[key], list):
                data[key].append(line.split("-", 1)[1].strip().strip("\"'"))
            continue
        m = re.match(r"^([A-Za-z_$][\w-]*):\s*(.*)$", line)
        if m:
            key, value = m.group(1), m.group(2).strip()
            if value.startswith("["):
                data[key] = [v.strip().strip("\"'") for v in value[1:-1].split(",") if v.strip()]
            else:
                data[key] = value.strip("\"'") if value else []
    return data


def source_files() -> list[Path]:
    return [p for p in sorted(ROOT.rglob("*")) if p.is_file() and not (set(p.relative_to(ROOT).parts) & EXCLUDE_DIRS)]


def zip_files(output: Path, mapping: dict[str, Path]) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for name in sorted(mapping):
            info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            archive.writestr(info, mapping[name].read_bytes())


def vendor_packages(name: str, targets: list[str]) -> dict[str, int]:
    apm = shutil.which("apm")
    if not apm:
        raise SystemExit("apm CLI not found on PATH; use --no-vendor to skip vendor packages")
    counts: dict[str, int] = {}
    for target in targets:
        with tempfile.TemporaryDirectory(prefix=f"pack-{target}-") as tmp:
            subprocess.run(["git", "init", "-q"], cwd=tmp, capture_output=True)
            proc = subprocess.run([apm, "install", "--target", target, str(ROOT)], cwd=tmp, capture_output=True, text=True)
            if proc.returncode != 0:
                raise SystemExit(f"apm install --target {target} failed:\n{proc.stdout}\n{proc.stderr}")
            files: dict[str, Path] = {}
            for path in Path(tmp).rglob("*"):
                rel = path.relative_to(tmp)
                if path.is_file() and not ({"apm_modules", ".git"} & set(rel.parts)) and rel.name not in ("apm.yml", "apm.lock.yaml", ".gitignore"):
                    files[rel.as_posix()] = path
            zip_files(DIST / f"{target}-{name}.zip", files)
            counts[target] = len(files)
    return counts


def frontmatter_description(path: Path) -> str:
    text = path.read_text(encoding="utf-8", errors="replace")
    if not text.startswith("---"):
        return ""
    m = re.search(r"^description:\s*(.+)$", text, re.M)
    return m.group(1).strip().strip("\"'") if m else ""


def purpose(rel: Path) -> str:
    if len(rel.parts) == 1 and rel.name in PURPOSE:
        return PURPOSE[rel.name]
    for folder, text in FOLDER_PURPOSE.items():
        if rel.as_posix().startswith(folder + "/"):
            desc = frontmatter_description(ROOT / rel) if rel.suffix == ".md" else ""
            return f"{text}: {desc}" if desc else text
    return "Pack file"


def catalog(name: str, version: str, files: list[Path], vendor_counts: dict[str, int]) -> None:
    lines = [f"# {name} {version}: artifact catalog", "",
             "Every file in this pack, with its purpose and location. Contents are in the files themselves.", "",
             "| ARTIFACT NAME | PURPOSE | LOCATION |", "|---|---|---|"]
    for path in files:
        rel = path.relative_to(ROOT)
        if rel.name == "AGENT-PACK-README.md":
            continue
        lines.append(f"| {rel.name} | {purpose(rel).replace('|', '/')} | {rel.as_posix()} |")
    lines += ["", "## Build outputs (dist/, not committed)", ""]
    for target, count in vendor_counts.items():
        lines.append(f"- {target}-{name}.zip: {count} files generated by `apm install --target {target}`")
    lines.append(f"- {name}-canonical.zip, {name}-prompt.zip, {name}-validation.zip, {name}-skills.zip, {name}-full-pack.zip, SHA256SUMS.txt")
    (ROOT / "AGENT-PACK-README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--no-vendor", action="store_true", help="skip apm-generated vendor packages")
    args = parser.parse_args()
    data = manifest()
    name, version = str(data["name"]), str(data["version"])
    targets_raw = data.get("targets", [])
    targets = [t for t in targets_raw if isinstance(t, str)] if isinstance(targets_raw, list) else []
    if DIST.exists():
        shutil.rmtree(DIST)
    DIST.mkdir()
    vendor_counts = {} if args.no_vendor else vendor_packages(name, targets)
    files = source_files()

    def rel(p: Path) -> str:
        return p.relative_to(ROOT).as_posix()

    zip_files(DIST / f"{name}-canonical.zip", {rel(p): p for p in files if rel(p) == "apm.yml" or rel(p).startswith(".apm/")})
    zip_files(DIST / f"{name}-prompt.zip", {"PORTABLE_AGENT_SKILL_PACK_AUTHORING_PROMPT.md": ROOT / "PORTABLE_AGENT_SKILL_PACK_AUTHORING_PROMPT.md"})
    validation = [p for p in files if rel(p) == "VALIDATION_REPORT.md" or rel(p).split("/")[0] in ("compatibility", "tests", "templates")]
    zip_files(DIST / f"{name}-validation.zip", {rel(p): p for p in validation})
    for skill in sorted(p for p in (ROOT / ".apm" / "skills").iterdir() if p.is_dir()):
        zip_files(DIST / "skills" / skill.name / "skill.zip", {p.relative_to(skill).as_posix(): p for p in skill.rglob("*") if p.is_file()})
    zip_files(DIST / f"{name}-skills.zip", {p.relative_to(DIST / "skills").as_posix(): p for p in (DIST / "skills").rglob("skill.zip")})
    catalog(name, version, files, vendor_counts)
    files = source_files()
    zip_files(DIST / f"{name}-full-pack.zip", {rel(p): p for p in files})
    sums = [f"{hashlib.sha256(p.read_bytes()).hexdigest()}  {p.relative_to(DIST).as_posix()}" for p in sorted(DIST.rglob("*.zip"))]
    (DIST / "SHA256SUMS.txt").write_text("\n".join(sums) + "\n", encoding="utf-8")
    print(f"built {len(sums)} archives in {DIST}; vendor packages: {vendor_counts}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
